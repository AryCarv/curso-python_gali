#SOMA
soma = primeiro_numero + segundo_numero
print(f'A soma dos dois números é: {soma}')

#SUBTRAÇÃO
sub = primeiro_numero - segundo_numero
print(f'A subtração dos dois números é: {sub}')

#MULTIPLICAÇÃO
mult = primeiro_numero * segundo_numero
print(f'A multiplicação dos dois números é: {mult}')

#DIVISÃO
div = primeiro_numero / segundo_numero
print(f'A divisão dos dois números é: {div}')

#RESTO DA DIVISÃO
resto = primeiro_numero % segundo_numero
print(f'O resto da divisão dos dois números é: {resto}')

#POTENCIAÇÃO
pot = primeiro_numero ** segundo_numero
print(f'A potenciação dos dois números é: {pot}')

#PARTE INTEIRA DA DIVISÃO
parte_inteira = primeiro_numero // segundo_numero
print(f'A parte inteira da divisão dos dois números é: {parte_inteira}')

